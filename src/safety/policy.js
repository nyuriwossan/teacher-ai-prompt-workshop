/** 「〇〇さん」「〇〇くん」などの呼び方 */
const HONORIFIC = /([一-龥ぁ-んァ-ヶーA-Za-z]{1,8})(さん|くん|君|ちゃん|様|さま|氏)(?![一-龥ぁ-ん]{0,1}(?:たち|方|がた))/g;

function collectStrings(value, out = []) {
  if (value === null || value === undefined) return out;
  if (typeof value === 'string') out.push(value);
  else if (Array.isArray(value)) value.forEach((v) => collectStrings(v, out));
  else if (typeof value === 'object') Object.values(value).forEach((v) => collectStrings(v, out));
  return out;
}

/**
 * 入力値（自由記述）から、個人情報・配慮を要する情報が含まれる可能性を調べる。
 * 返すのは「種類」だけで、検出した文字列そのものは画面に出さない。
 * @param {object} values フォームの値
 * @returns {{found: boolean, kinds: string[]}}
 */
export function scanForSensitive(values) {
  const text = collectStrings(values).join('\n');
  const kinds = new Set();
  for (const p of PATTERNS) if (p.re.test(text)) kinds.add(p.label);
  let m;
  HONORIFIC.lastIndex = 0;
  while ((m = HONORIFIC.exec(text)) !== null) {
    if (!NAME_EXCLUDE.test(m[1])) { kinds.add('人の名前（〇〇さん・〇〇くん など）'); break; }
  }
  for (const group of SENSITIVE_WORDS) {
    if (group.words.some((w) => text.includes(w))) kinds.add(group.label);
  }
  return { found: kinds.size > 0, kinds: [...kinds] };
}

