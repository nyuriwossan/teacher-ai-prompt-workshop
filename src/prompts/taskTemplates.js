function deliveryLine(value, kind = 'doc') {
  switch (value) {
    case 'word':
      return kind === 'table'
        ? 'Wordの表として後から編集しやすい形にしてください。Wordファイル（.docx）を作成できる場合は作成し、できない場合はWordに貼り付けられる表（Markdownの表）で出力してください。'
        : 'Wordで後から編集しやすい体裁（見出し・段落・箇条書きを明確に）にしてください。Wordファイル（.docx）を作成できる場合は作成し、できない場合は見出しと本文をそのまま貼り付けられるテキストで出力してください。';
    case 'gdocs':
      return 'Googleドキュメントに貼り付けて編集しやすい形（見出し・段落・箇条書き）のテキストで出力してください。';
    case 'pdf':
      return '印刷用のPDFを作成できる場合はPDFで出力し、できない場合はWord等に貼り付けて印刷できるテキストで出力してください。';
    case 'excel':
      return 'Excel・Googleスプレッドシートで編集できる形にしてください。ファイル（.xlsx）を作成できる場合は作成し、できない場合はスプレッドシートに貼り付けられるタブ区切りのテキストと、確認用のMarkdownの表の両方で出力してください。';
    case 'text':
      return kind === 'table'
        ? 'コピーしてそのまま貼り付けられる表（Markdownの表）で出力してください。'
        : 'コピーしてそのまま使えるテキストで出力してください。';
    default:
      return null;
  }
}

/** 「次の内容を含めてください」のような見出しつきの入れ子リスト */
function includeList(lead, parts) {
  const items = parts.filter(Boolean);
  if (!items.length) return null;
  return [lead, ...items.map((p) => `－ ${p}`)].join('\n');
}

function monoLine(on) {
  return on ? 'モノクロ印刷でも読みやすいよう、色に頼った強調は避け、太字・罫線・囲み・記号で区別してください。' : null;
}

/** 学級通信の文字数の目安（あくまで目安として依頼文に書く） */
export function newsletterCharBudget(paper, pages, photoSlots, articleCount, hasNotices) {
  const perPage = { A4縦: 1200, A4横: 1200, B4縦: 1800, B4横: 1800, B5縦: 900 }[paper] || 1200;
  const pageCount = pages && pages.startsWith('2') ? 2 : 1;
  let total = perPage * pageCount - Number(photoSlots || 0) * 200 - (hasNotices ? 150 : 0);
  total = Math.max(400, Math.round(total / 100) * 100);
  const per = Math.max(150, Math.floor(total / Math.max(1, articleCount) / 50) * 50);
  return { total, per };
}

